#!/usr/bin/env node
/**
 * Writes `.env.local` from `supabase status`.
 *
 *   npx supabase start
 *   npm run supabase:env
 *
 * The app and the E2E auth suite both need these values; keeping them out of
 * git means a cloned repo cannot accidentally point at someone else's project.
 */
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

function readStatus() {
  const output = execSync("npx supabase status -o env", {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });

  const values = {};
  for (const line of output.split(/\r?\n/)) {
    const separator = line.indexOf("=");
    if (separator === -1) continue;
    const key = line.slice(0, separator).trim();
    const value = line
      .slice(separator + 1)
      .trim()
      .replace(/^"(.*)"$/, "$1");
    if (key) values[key] = value;
  }
  return values;
}

const values = readStatus();

const apiUrl = values.API_URL ?? "http://127.0.0.1:54321";
const publishableKey = values.PUBLISHABLE_KEY ?? values.ANON_KEY;
const secretKey = values.SECRET_KEY ?? values.SERVICE_ROLE_KEY;
const dbUrl = values.DB_URL ?? "postgresql://postgres:postgres@127.0.0.1:54322/postgres";

if (!publishableKey || !secretKey) {
  console.error("Could not read Supabase keys. Is `npx supabase start` running?");
  process.exit(1);
}

const contents = `# Generated by \`npm run supabase:env\`. Do not commit.
# Local Supabase stack — see supabase/config.toml.

NEXT_PUBLIC_SUPABASE_URL=${apiUrl}
NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${publishableKey}
SUPABASE_SERVICE_ROLE_KEY=${secretKey}
SUPABASE_DB_URL=${dbUrl}

# Disposable Postgres used by \`npm run test:db\` (docker-compose.test.yml).
DATABASE_URL=postgresql://postgres:postgres@127.0.0.1:54331/postgres
`;

writeFileSync(".env.local", contents, "utf8");

console.log(`Wrote .env.local (${apiUrl})`);
